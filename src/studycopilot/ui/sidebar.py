    def set_capture_shortcut(self, shortcut: str | None):
        self.selection_label.setText("辅助文字 · " + (shortcut or "手动粘贴"))

    def set_image(self, image: QPixmap | None):
        self.image = image or QPixmap()
        self.update_thumbnail()

    def update_thumbnail(self):
        if self.image.isNull():
            self.thumbnail.setPixmap(QPixmap())
            self.thumbnail.setText("框选教材中需要阅读的区域\n正文、公式、电路图可以一起截")
        else:
            self.thumbnail.setPixmap(self.image.scaled(
                self.thumbnail.size() - QSize(18, 18), Qt.AspectRatioMode.KeepAspectRatio,
                Qt.TransformationMode.SmoothTransformation))

    def resizeEvent(self, event):
        super().resizeEvent(event)
        self.update_thumbnail()

    def place_right(self):
        screen = QApplication.primaryScreen()
        if screen:
            rect = screen.availableGeometry()
            self.resize(430, min(820, rect.height() - 40))
            self.move(rect.right() - self.width() - 15, rect.top() + 20)

    def closeEvent(self, event):
        self.closing.emit()
        event.accept()
