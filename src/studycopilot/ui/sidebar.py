def section(text: str) -> QLabel:
    label = QLabel(text)
    label.setObjectName("Section")
    return label


def row(*widgets) -> QHBoxLayout:
    layout = QHBoxLayout()
    for widget in widgets:
        layout.addWidget(widget)
    return layout


